"""Train and evaluate two configurations on the waste dataset.

  1. Baseline CNN - a small network trained from scratch, no augmentation
  2. Improved CNN - pretrained MobileNetV2, fine-tuned, with data augmentation

Saves the models, graphs, per-class results and results/summary.md.   Run:  python train.py
"""
import copy
import json
import time
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from PIL import Image


# ===== HELPERS START (need only numpy / matplotlib) =====
def metrics_from(probs, true, classes):
    n = len(classes)
    pred = probs.argmax(1)
    cm = np.zeros((n, n), dtype=int)
    for t, p in zip(true, pred):
        cm[t, p] += 1
    per_class = {}
    for i, name in enumerate(classes):
        tp, col, row = int(cm[i, i]), int(cm[:, i].sum()), int(cm[i].sum())
        precision = tp / col if col else 0.0
        recall = tp / row if row else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        per_class[name] = {'precision': precision, 'recall': recall, 'f1': f1, 'support': row}
    return float((pred == true).mean()), cm, per_class


def confidence_table(probs, true):
    conf, pred = probs.max(1), probs.argmax(1)
    ok = pred == true
    rows = []
    for lo, hi, label in [(0.0, 0.5, 'below 50%'), (0.5, 0.8, '50% to 80%'),
                          (0.8, 0.95, '80% to 95%'), (0.95, 1.01, '95% and above')]:
        mask = (conf >= lo) & (conf < hi)
        rows.append((label, int(mask.sum()), int(ok[mask].sum())))
    wrong_mean = float(conf[~ok].mean()) if (~ok).any() else 0.0
    wrong_high = int(((conf >= 0.9) & ~ok).sum())
    return rows, wrong_mean, wrong_high


def plot_curves(histories, path):
    fig, axes = plt.subplots(len(histories), 2, figsize=(11, 4 * len(histories)))
    axes = np.atleast_2d(axes)
    for row, (name, h) in enumerate(histories.items()):
        epochs = list(range(1, len(h['train_loss']) + 1))
        axes[row, 0].plot(epochs, h['train_loss'], label='Train')
        axes[row, 0].plot(epochs, h['val_loss'], label='Validation')
        axes[row, 0].set_title(f'{name}: loss')
        axes[row, 1].plot(epochs, [a * 100 for a in h['train_acc']], label='Train')
        axes[row, 1].plot(epochs, [a * 100 for a in h['val_acc']], label='Validation')
        axes[row, 1].set_title(f'{name}: accuracy (%)')
        for ax in axes[row]:
            if h.get('stage2_start'):
                ax.axvline(h['stage2_start'] + 0.5, color='gray', linestyle=':', label='fine-tuning starts')
            ax.set_xlabel('Epoch')
            ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def plot_cm(cm, classes, title, path):
    fig, ax = plt.subplots(figsize=(6.5, 5.5))
    im = ax.imshow(cm, cmap='Blues')
    fig.colorbar(im, ax=ax)
    ax.set_xticks(range(len(classes)))
    ax.set_xticklabels(classes, rotation=45, ha='right')
    ax.set_yticks(range(len(classes)))
    ax.set_yticklabels(classes)
    ax.set_xlabel('Predicted')
    ax.set_ylabel('True')
    ax.set_title(title)
    for i in range(len(classes)):
        for j in range(len(classes)):
            ax.text(j, i, str(cm[i, j]), ha='center', va='center',
                    color='white' if cm[i, j] > cm.max() / 2 else 'black')
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def plot_failures(rows, path):
    fig, axes = plt.subplots(2, 5, figsize=(14, 6.5))
    for ax in axes.flat:
        ax.axis('off')
    for ax, r in zip(axes.flat, rows):
        ax.imshow(Image.open(r['path']).convert('RGB'))
        ax.set_title(f"True: {r['true']}\nPred: {r['pred']} ({r['conf'] * 100:.0f}%)", fontsize=9)
    fig.suptitle('Most confident mistakes of the improved CNN (test set)')
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def pct(x):
    return f'{x * 100:.2f}%'


def build_summary(classes, infos, per_class, conf_rows, wrong_mean, wrong_high, fail_rows, dataset_md):
    L = ['# Evaluation summary (generated by train.py)', '']
    L += ['## 1. Dataset', '', dataset_md.strip() if dataset_md else '(run prepare_data.py to create the dataset table)', '']
    L += ['## 2. Model configurations', '',
          '| Configuration | Description | Parameters | Training time | Best epoch |', '|---|---|---|---|---|']
    for i in infos:
        L.append(f"| {i['name']} | {i['description']} | {i['params']:,} | {i['seconds'] / 60:.1f} min | {i['best_epoch']} |")
    L += ['', '## 3. Accuracy', '', '| Configuration | Validation accuracy | Test accuracy |', '|---|---|---|']
    for i in infos:
        L.append(f"| {i['name']} | {pct(i['val_acc'])} | {pct(i['test_acc'])} |")
    L += ['', 'The best epoch was chosen on validation accuracy. The test set was used once, at the end.', '']
    L += ['## 4. Per-class results on the test set', '']
    for name, table in per_class.items():
        L += [f'### {name}', '', '| Class | Precision | Recall | F1 | Test images |', '|---|---|---|---|---|']
        for c in classes:
            r = table[c]
            L.append(f"| {c} | {pct(r['precision'])} | {pct(r['recall'])} | {pct(r['f1'])} | {r['support']} |")
        L.append('')
    L += ['## 5. Do high scores mean the answer is correct? (improved CNN, test set)', '',
          '| Model score | Predictions | Correct | Share correct |', '|---|---|---|---|']
    for label, n, ok in conf_rows:
        share = pct(ok / n) if n else 'no predictions'
        L.append(f'| {label} | {n} | {ok} | {share} |')
    L += ['', f'- Average score of the wrong predictions: {pct(wrong_mean)}',
          f'- Wrong predictions made with a score of 90% or more: {wrong_high}', '']
    L += ['## 6. Failure examples (most confident mistakes of the improved CNN)', '',
          '| File | True class | Predicted | Score |', '|---|---|---|---|']
    for r in fail_rows:
        L.append(f"| {r['file']} | {r['true']} | {r['pred']} | {pct(r['conf'])} |")
    return '\n'.join(L) + '\n'
# ===== HELPERS END =====


import torch
import torch.nn as nn
from torch.utils.data import DataLoader
from torchvision import datasets

from common import (HERE, MODELS_DIR, MODEL_FILES, BaselineCNN, aug_transform, count_params,
                    eval_transform, make_improved)


def main():
    torch.manual_seed(42)
    np.random.seed(42)
    data, results = HERE / 'dataset', HERE / 'results'
    if not (data / 'train').is_dir():
        raise SystemExit('dataset/ folder not found. Run prepare_data.py first.')
    results.mkdir(exist_ok=True)
    MODELS_DIR.mkdir(exist_ok=True)

    train_plain = datasets.ImageFolder(data / 'train', eval_transform)     # baseline: no augmentation
    train_aug = datasets.ImageFolder(data / 'train', aug_transform)        # improved: augmentation
    val_ds = datasets.ImageFolder(data / 'val', eval_transform)
    test_ds = datasets.ImageFolder(data / 'test', eval_transform)
    classes = train_plain.classes
    json.dump(classes, open(HERE / 'classes.json', 'w'))
    print('Classes:', classes)
    print(f'Train: {len(train_plain)} | Validation: {len(val_ds)} | Test: {len(test_ds)}')

    val_loader = DataLoader(val_ds, batch_size=64)
    test_loader = DataLoader(test_ds, batch_size=64)
    loss_fn = nn.CrossEntropyLoss()

    def run_eval(model, loader):
        model.eval()
        total, correct, n = 0.0, 0, 0
        with torch.no_grad():
            for x, y in loader:
                out = model(x)
                total += loss_fn(out, y).item() * len(y)
                correct += (out.argmax(1) == y).sum().item()
                n += len(y)
        return total / n, correct / n

    def fit(model, loader, optimizer, epochs, hist, best, freeze_features=False):
        for _ in range(epochs):
            model.train()
            if freeze_features:
                model.features.eval()          # keep the frozen pretrained part fixed
            run_loss, correct, n = 0.0, 0, 0
            for x, y in loader:
                optimizer.zero_grad()
                out = model(x)
                loss = loss_fn(out, y)
                loss.backward()
                optimizer.step()
                run_loss += loss.item() * len(y)
                correct += (out.argmax(1) == y).sum().item()
                n += len(y)
            v_loss, v_acc = run_eval(model, val_loader)
            hist['train_loss'].append(run_loss / n)
            hist['train_acc'].append(correct / n)
            hist['val_loss'].append(v_loss)
            hist['val_acc'].append(v_acc)
            epoch = len(hist['val_acc'])
            if v_acc > best['acc']:
                best.update(acc=v_acc, state=copy.deepcopy(model.state_dict()), epoch=epoch)
            print(f"  Epoch {epoch:2d}: train acc={correct / n * 100:.1f}%, "
                  f"val loss={v_loss:.3f}, val acc={v_acc * 100:.1f}%")

    def new_hist():
        return {'train_loss': [], 'val_loss': [], 'train_acc': [], 'val_acc': []}

    def predict_probs(model, loader):
        model.eval()
        out = []
        with torch.no_grad():
            for x, _ in loader:
                out.append(torch.softmax(model(x), dim=1))
        return torch.cat(out).numpy()

    # ---------- Configuration 1: baseline CNN ----------
    print('\n=== Baseline CNN (from scratch, no augmentation) ===')
    baseline = BaselineCNN(len(classes))
    base_hist, base_best = new_hist(), {'acc': -1.0, 'state': None, 'epoch': 0}
    start = time.time()
    fit(baseline, DataLoader(train_plain, batch_size=32, shuffle=True),
        torch.optim.Adam(baseline.parameters(), lr=1e-3), 15, base_hist, base_best)
    base_seconds = time.time() - start
    baseline.load_state_dict(base_best['state'])
    torch.save(baseline.state_dict(), MODELS_DIR / MODEL_FILES['baseline'])

    # ---------- Configuration 2: improved CNN ----------
    print('\n=== Improved CNN (pretrained MobileNetV2 + augmentation) ===')
    improved = make_improved(len(classes), pretrained=True)
    for p in improved.features.parameters():
        p.requires_grad = False
    imp_hist, imp_best = new_hist(), {'acc': -1.0, 'state': None, 'epoch': 0}
    aug_loader = DataLoader(train_aug, batch_size=32, shuffle=True)
    start = time.time()
    print('Stage 1: training only the new output layer')
    fit(improved, aug_loader, torch.optim.Adam(improved.classifier.parameters(), lr=1e-3), 4,
        imp_hist, imp_best, freeze_features=True)
    imp_hist['stage2_start'] = len(imp_hist['val_acc'])
    print('Stage 2: fine-tuning the last blocks of the pretrained network')
    for p in improved.features[-4:].parameters():
        p.requires_grad = True
    optimizer = torch.optim.Adam([{'params': improved.features[-4:].parameters(), 'lr': 1e-4},
                                  {'params': improved.classifier.parameters(), 'lr': 1e-4}])
    fit(improved, aug_loader, optimizer, 6, imp_hist, imp_best)
    imp_seconds = time.time() - start
    improved.load_state_dict(imp_best['state'])
    torch.save(improved.state_dict(), MODELS_DIR / MODEL_FILES['improved'])

    # ---------- Evaluation on the test set (used once) ----------
    true = np.array(test_ds.targets)
    base_probs = predict_probs(baseline, test_loader)
    imp_probs = predict_probs(improved, test_loader)
    base_acc, base_cm, base_pc = metrics_from(base_probs, true, classes)
    imp_acc, imp_cm, imp_pc = metrics_from(imp_probs, true, classes)

    plot_curves({'Baseline CNN': base_hist, 'Improved CNN': imp_hist}, results / 'training_curves.png')
    plot_cm(base_cm, classes, f'Baseline CNN (test accuracy {base_acc * 100:.1f}%)',
            results / 'confusion_matrix_baseline.png')
    plot_cm(imp_cm, classes, f'Improved CNN (test accuracy {imp_acc * 100:.1f}%)',
            results / 'confusion_matrix_improved.png')

    conf, pred = imp_probs.max(1), imp_probs.argmax(1)
    wrong = np.nonzero(pred != true)[0]
    wrong = wrong[np.argsort(-conf[wrong])][:10]                  # most confident mistakes first
    fail_rows = [{'file': Path(test_ds.samples[i][0]).name, 'path': test_ds.samples[i][0],
                  'true': classes[true[i]], 'pred': classes[pred[i]], 'conf': float(conf[i])} for i in wrong]
    if fail_rows:
        plot_failures(fail_rows, results / 'failure_examples.png')
    conf_rows, wrong_mean, wrong_high = confidence_table(imp_probs, true)

    infos = [
        {'name': 'Baseline CNN', 'description': '3 conv blocks trained from scratch, no augmentation',
         'params': count_params(baseline), 'seconds': base_seconds, 'best_epoch': base_best['epoch'],
         'val_acc': base_best['acc'], 'test_acc': base_acc},
        {'name': 'Improved CNN', 'description': 'MobileNetV2 pretrained + fine-tuning + augmentation + dropout',
         'params': count_params(improved), 'seconds': imp_seconds, 'best_epoch': imp_best['epoch'],
         'val_acc': imp_best['acc'], 'test_acc': imp_acc},
    ]
    ds_file = results / 'dataset_summary.md'
    dataset_md = ds_file.read_text() if ds_file.exists() else ''
    summary = build_summary(classes, infos, {'Baseline CNN': base_pc, 'Improved CNN': imp_pc},
                            conf_rows, wrong_mean, wrong_high, fail_rows, dataset_md)
    (results / 'summary.md').write_text(summary)
    json.dump({'classes': classes, 'models': infos, 'per_class': {'baseline': base_pc, 'improved': imp_pc},
               'confusion_matrix': {'baseline': base_cm.tolist(), 'improved': imp_cm.tolist()},
               'history': {'baseline': base_hist, 'improved': imp_hist}},
              open(results / 'metrics.json', 'w'), indent=2)

    print('\n' + summary)
    print('Saved models/, classes.json and results/ (summary.md, metrics.json, 4 images)')


if __name__ == '__main__':
    main()